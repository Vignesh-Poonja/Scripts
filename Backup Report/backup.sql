SELECT
    DATABASE_NAME,
    BACKUP_DATE,
    STATE_NAME,
    DESTINATION_TYPE_NAME,
    SIZE_GB
FROM
(
    SELECT
        C.DATABASE_NAME,
        TO_VARCHAR(C.SYS_START_TIME) AS BACKUP_DATE,
        C.STATE_NAME,
        MAX(F.DESTINATION_TYPE_NAME) AS DESTINATION_TYPE_NAME,
        ROUND(SUM(F.BACKUP_SIZE)/1024/1024/1024,2) AS SIZE_GB,
        ROW_NUMBER() OVER
        (
            PARTITION BY C.DATABASE_NAME
            ORDER BY C.SYS_START_TIME DESC
        ) RN
    FROM SYS_DATABASES.M_BACKUP_CATALOG C
    JOIN SYS_DATABASES.M_BACKUP_CATALOG_FILES F
      ON C.BACKUP_ID = F.BACKUP_ID
    WHERE C.ENTRY_TYPE_NAME='complete data backup'
      AND C.STATE_NAME='successful'
    GROUP BY
        C.DATABASE_NAME,
        C.BACKUP_ID,
        C.SYS_START_TIME,
        C.STATE_NAME
)
WHERE RN = 1
ORDER BY DATABASE_NAME;
